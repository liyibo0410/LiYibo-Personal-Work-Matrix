def main() -> int:
    if DST.exists():
        shutil.rmtree(DST)
    (DST / "slides").mkdir(parents=True)
    for name in ("STORY.md", "DESIGN.md"):
        shutil.copy2(SRC / name, DST / name)

    misses: list[str] = []
    for idx in range(1, 15):
        text = (SRC / "slides" / f"{idx:02d}.slide").read_text(encoding="utf-8")
        for old, new in RULES:
            if old in text:
                text = text.replace(old, new)
        (DST / "slides" / f"{idx:02d}.slide").write_text(text, encoding="utf-8")

    # 统计未命中（仅提示，不阻断）
    joined = "\n".join((DST / "slides" / f"{i:02d}.slide").read_text(encoding="utf-8")
                       for i in range(1, 15))
    for old, _new in RULES:
        if old not in joined and old not in "".join(
            (SRC / "slides" / f"{i:02d}.slide").read_text(encoding="utf-8")
            for i in range(1, 15)
        ):
            misses.append(old)

    # 残留检查：客户版不应再出现课程口径字样
    leftovers = [kw for kw in ("各位老师", "课程结课答辩", "课程给的", "课程作业", "2026 届")
                 if kw in joined]
    print("改写完成 ->", DST)
    print("未命中的规则:", misses if misses else "无")
    print("残留课程口径字样:", leftovers if leftovers else "无")

    # 同步输出客户版说明
    with io.open(DST / "口径说明.md", "w", encoding="utf-8") as handle:
        handle.write(
            "# 客户汇报版口径说明\n\n"
            "本目录由答辩版定向改写而来，**内容与实测数据完全一致**，仅调整立场与话术：\n\n"
            "| 项 | 答辩版 | 客户版 |\n|---|---|---|\n"
            "| 场合 | 课程结课答辩 | 项目验收汇报 |\n"
            "| 称呼 | 各位老师 | 各位领导 |\n"
            "| 三段结构 | 三个真难点 | 三项可控性设计 |\n"
            "| 第 9 页 | 自研增量（含课程对比） | 工程化保障 |\n"
            "| 第 14 页 | 已知限制·下一步 | 交付边界与后续规划 |\n"
            "| 页脚 | 课程结课答辩 | 项目验收汇报 |\n\n"
            "未改动：58 项验收用例与结果、pytest 117 passed、四条实测证据、"
            "安全与合规声明、所有技术描述与代码标识符。\n"
        )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
