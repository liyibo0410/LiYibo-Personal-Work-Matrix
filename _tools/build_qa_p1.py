def main():
    # 备份原始 3 条
    if os.path.exists(SRC) and not os.path.exists(BAK):
        shutil.copy2(SRC, BAK)
        print(f"[backup] {SRC} -> {BAK}")

    with io.open(OUT, "w", encoding="utf-8-sig", newline="") as f:
        w = csv.writer(f)
        w.writerow(["question", "ground_truth"])
        for _, _, q, a in ROWS:
            w.writerow([q, a])

    # 统计
    from collections import Counter
    diff = Counter(d for d, _, _, _ in ROWS)
    dim = Counter(m for _, m, _, _ in ROWS)

    print(f"\n[done] 写入 {OUT}")
    print(f"  总题数: {len(ROWS)}（原 3 条 + 新增 {len(ROWS)-3} 条）")
    print(f"  难度分布: {dict(diff)}")
    print(f"  维度数: {len(dim)}")
    for k, v in sorted(dim.items(), key=lambda x: -x[1]):
        print(f"    {k}: {v}")

    # 自检：所有 question 必须带产品名前缀（避免走消歧分支）
    bad = [q for _, _, q, _ in ROWS if not q.startswith("hak 180 烫金机")]
    print(f"\n[自检] 缺少产品名前缀的题目: {len(bad)}")
    for q in bad:
        print(f"    ! {q}")

    # 自检：无空答案、无重复
    empties = [q for _, _, q, a in ROWS if not a.strip()]
    dupes = [q for q, c in Counter(q for _, _, q, _ in ROWS).items() if c > 1]
    print(f"[自检] 空答案: {len(empties)}  重复题目: {len(dupes)}")
    for q in dupes:
        print(f"    ! {q}")


if __name__ == "__main__":
    main()
